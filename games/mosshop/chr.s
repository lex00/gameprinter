; Moss Hop: pattern table (CHR ROM). Original art, drawn here as text.
;
; Each tile is eight rows of eight pixels. A pixel is a color index from its
; palette: '.' is 0 (transparent for sprites, the sky for the background),
; '1' to '3' are the palette's other colors. The tile macro turns the rows
; into the NES's two bit planes, so the art stays readable in the source.

.macro plane_byte row, bit
    .local value
    value .set 0
    .repeat 8, i
        value .set value | (((((.strat(row, i) - '0') * (.strat(row, i) <> '.')) >> bit) & 1) << (7 - i))
    .endrepeat
    .byte value
.endmacro

.macro tile r0, r1, r2, r3, r4, r5, r6, r7
    plane_byte r0, 0
    plane_byte r1, 0
    plane_byte r2, 0
    plane_byte r3, 0
    plane_byte r4, 0
    plane_byte r5, 0
    plane_byte r6, 0
    plane_byte r7, 0
    plane_byte r0, 1
    plane_byte r1, 1
    plane_byte r2, 1
    plane_byte r3, 1
    plane_byte r4, 1
    plane_byte r5, 1
    plane_byte r6, 1
    plane_byte r7, 1
.endmacro

