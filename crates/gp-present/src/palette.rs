//! The RGB a console's color numbers are drawn in. Every runtime that turns
//! a color number into RGB reads it from here: generated games (through
//! the generator's pictures), the interpreter preview, and the comparisons
//! that put the original's picture beside the rebuild's. The original's
//! emulator draws with the same table (`gp-nes`'s tests check it), so the
//! same color number is the same RGB in the original and the rebuild.

