#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nes_colors_have_black_grays_and_white() {
        assert_eq!(NES[0x0F], [0x03, 0x03, 0x03]);
        assert_eq!(NES[0x20], [0xFF, 0xFF, 0xFF]);
        assert_eq!(NES[0x30], [0xFF, 0xFF, 0xFF]);
        // The grays $00, $10 and $2D are gray and get lighter in that order.
        let gray = |c: usize| NES[c][0] == NES[c][1] && NES[c][1] == NES[c][2];
        assert!(gray(0x00) && gray(0x10) && gray(0x2D));
        assert!(NES[0x2D][0] < NES[0x00][0] && NES[0x00][0] < NES[0x10][0]);
    }
}
