/// Frames whose distance is over `from` and up to `to` (the first bin is
/// from 0, within the tolerance, both included).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Bin {
    pub from: String,
    pub to: String,
    pub frames: u64,
}

/// A scenario's score in one line: measures exact of measures, and the
/// frames together as a share of every measure's frames.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Headline {
    pub exact: u64,
    pub measures: u64,
    /// Together in tenths of a percent, so it stays a whole number.
    pub together_permille: u64,
    /// "9/10 measures, 96%".
    pub says: String,
}

/// The doubling bins the game view's histograms use (editor/src/lockfold.ts):
/// within the tolerance, then each bin twice as wide, from a 256th of a
/// pixel past it, up to 256 px and everything over.
pub fn bins(distance: &[Fx], tolerance: Fx) -> Vec<Bin> {
    let mut out = vec![Bin {
        from: "0".into(),
        to: tolerance.to_string(),
        frames: 0,
    }];
    let mut edges = Vec::new();
    let mut e: i64 = 1 << 8;
    while e <= 256 << 16 {
        if e > tolerance.raw() {
            edges.push(e);
        }
        e <<= 1;
    }
    let mut lo = tolerance.raw();
    for &e in &edges {
        out.push(Bin {
            from: Fx::from_raw(lo).to_string(),
            to: Fx::from_raw(e).to_string(),
            frames: 0,
        });
        lo = e;
    }
    out.push(Bin {
        from: Fx::from_raw(lo).to_string(),
        to: String::new(),
        frames: 0,
    });
    for d in distance {
        let k = if *d <= tolerance {
            0
        } else {
            edges
                .iter()
                .position(|e| d.raw() <= *e)
                .map_or(edges.len() + 1, |i| i + 1)
        };
        out[k].frames += 1;
    }
    // Empty bins past the last used one say nothing.
    while out.len() > 1 && out.last().is_some_and(|b| b.frames == 0) {
        out.pop();
    }
    out
}

fn measures(ls: &Lockstep, start: &Start, catalog: &Catalog) -> (Vec<MeasureScore>, Headline) {
    let mut out = Vec::new();
    let (mut exact, mut together, mut total) = (0u64, 0u64, 0u64);
    for (i, p) in ls.paths.iter().enumerate() {
        let n = p.distance.len() as u64;
        let first = p.first_split.map(|at| {
            let of = ls.frames[at].1;
            let split = ls
                .splits
                .iter()
                .find(|s| s.at == at)
                .and_then(|s| s.paths.iter().find(|q| q.path == p.path));
            MeasureSplit {
                frame: of.saturating_sub(start.original_frame),
                original: split.map_or(String::new(), |q| show(&q.original)),
                model: split.map_or(String::new(), |q| show(&q.model)),
            }
        });
        if p.within == n {
            exact += 1;
        }
        let named = ls
            .values
            .iter()
            .any(|(o, m)| matches!(o[i], Value::Text(_)) || matches!(m[i], Value::Text(_)));
        together += p.within;
        total += n;
        out.push(MeasureScore {
            path: p.path.clone(),
            together: p.within,
            total: n,
            tolerance: p.tolerance.to_string(),
            max: p.max.to_string(),
            mean: p.mean().to_string(),
            first,
            bins: bins(&p.distance, p.tolerance),
            owners: lockstep::owners(catalog, &p.path)
                .iter()
                .map(|o| (*o).to_owned())
                .collect(),
            distance: p.distance.iter().map(ToString::to_string).collect(),
            original: ls.values.iter().map(|(o, _)| curve_text(&o[i])).collect(),
            model: ls.values.iter().map(|(_, m)| curve_text(&m[i])).collect(),
            original_names: if named {
                ls.values.iter().map(|(o, _)| name_text(&o[i])).collect()
            } else {
                Vec::new()
            },
            model_names: if named {
                ls.values.iter().map(|(_, m)| name_text(&m[i])).collect()
            } else {
                Vec::new()
            },
        });
    }
    let permille = (together * 1000).checked_div(total).unwrap_or(1000);
    let headline = Headline {
        exact,
        measures: out.len() as u64,
        together_permille: permille,
        says: format!("{exact}/{} measures, {}%", out.len(), permille / 10),
    };
    (out, headline)
}

/// Runs one scenario on both: `original` stands at the start's frame (it
/// is forked, not moved), `model` is fresh. Free run, so the distances are
/// the model's own.
#[allow(clippy::too_many_arguments)]
pub fn run<O: Runtime, M: Runtime>(
    original: &O,
    model: &mut M,
    spec: &Spec,
    mapping: &Mapping,
    start: &Start,
    scenario: &Scenario,
    tolerance: &[Fx],
    catalog: &Catalog,
) -> Result<(Outcome, Lockstep), String> {
    run_with(
        original, model, spec, mapping, start, scenario, tolerance, catalog, None,
    )
}

/// [`run`] with the screen measure, when `screens` draws the pictures.
#[allow(clippy::too_many_arguments)]
pub fn run_with<O: Runtime, M: Runtime>(
    original: &O,
    model: &mut M,
    spec: &Spec,
    mapping: &Mapping,
    start: &Start,
    scenario: &Scenario,
    tolerance: &[Fx],
    catalog: &Catalog,
    screens: Option<&mut dyn lockstep::Screens<O, M>>,
) -> Result<(Outcome, Lockstep), String> {
    run_stopping(
        original, model, spec, mapping, start, scenario, tolerance, catalog, screens, false,
    )
}

/// [`run_with`]; with `stop`, the run ends on its first split
/// ([`Options::stop_at_split`]) and the outcome says it `stopped` there, so
/// its counts cover the frames to the split. A run that doesn't split is
/// the whole run either way.
#[allow(clippy::too_many_arguments)]
pub fn run_stopping<O: Runtime, M: Runtime>(
    original: &O,
    model: &mut M,
    spec: &Spec,
    mapping: &Mapping,
    start: &Start,
    scenario: &Scenario,
    tolerance: &[Fx],
    catalog: &Catalog,
    screens: Option<&mut dyn lockstep::Screens<O, M>>,
    stop: bool,
) -> Result<(Outcome, Lockstep), String> {
    let inputs = scenario.inputs()?;
    let mut o = original.fork();
    let opts = Options {
        mode: Mode::Free,
        tolerance: tolerance.to_vec(),
        values: true,
        stop_at_split: stop,
        ..Options::default()
    };
    let ls =
        lockstep::lockstep_from_with(&mut o, model, spec, mapping, start, &inputs, &opts, screens)?;
    let mut out = outcome(scenario, start, &ls, catalog);
    out.stopped = stop && !ls.splits.is_empty();
    Ok((out, ls))
}

/// A scenario's result from its lockstep.
pub fn outcome(scenario: &Scenario, start: &Start, ls: &Lockstep, catalog: &Catalog) -> Outcome {
    let mut score = 0u64;
    for p in &ls.paths {
        score += p.distance.iter().filter(|d| **d > p.tolerance).count() as u64;
    }
    let first = ls.splits.first().map(|s| {
        // The scenario's own mechanic's measure first, if it split.
        let own = |p: &&lockstep::SplitPath| {
            lockstep::owners(catalog, &p.path)
                .first()
                .is_some_and(|o| *o == scenario.mechanic)
        };
        let p = s.paths.iter().find(own).unwrap_or(&s.paths[0]);
        FirstSplit {
            frame: s.original_frame.saturating_sub(start.original_frame),
            original_frame: s.original_frame,
            path: p.path.clone(),
            original: show(&p.original),
            model: show(&p.model),
            distance: p.distance.to_string(),
            mechanic: lockstep::owners(catalog, &p.path)
                .first()
                .map_or("(unowned)".to_owned(), |o| (*o).to_owned()),
            paths: s.paths.iter().map(|p| p.path.clone()).collect(),
        }
    });
    let says = match &first {
        None => format!("{}: matches exactly", scenario.name),
        Some(f) => format!("{}: {}", scenario.name, apart(f)),
    };
    let (measures, headline) = measures(ls, start, catalog);
    let mut moved: Vec<String> = Vec::new();
    for (i, p) in ls.paths.iter().enumerate() {
        let first = ls.values.first().map(|(o, _)| &o[i]);
        if ls.values.iter().any(|(o, _)| Some(&o[i]) != first)
            && let Some(m) = lockstep::owners(catalog, &p.path).first()
            && !moved.iter().any(|x| x == m)
        {
            moved.push((*m).to_owned());
        }
    }
    let paths: Vec<String> = ls.paths.iter().map(|p| p.path.clone()).collect();
    let tol: Vec<Fx> = ls.paths.iter().map(|p| p.tolerance).collect();
    let drift =
        lockstep::drift_point(ls, &lockstep::drift_thresholds(&paths, &tol, &[]), 0).map(|d| {
            DriftAt {
                frame: d.original_frame.saturating_sub(start.original_frame),
                original_frame: d.original_frame,
                path: d.path,
                distance: d.distance.to_string(),
                threshold: d.threshold.to_string(),
            }
        });
    Outcome {
        bodies: bodies(ls, start.original_frame),
        tracks: tracks(ls, start.original_frame),
        drift,
        moved,
        measures,
        headline,
        id: scenario.id.clone(),
        exact: first.is_none(),
        score,
        measured: ls.frames.len() as u64,
        original_from: start.original_frame,
        original_to: ls.frames.last().map_or(start.original_frame, |f| f.1),
        first,
        says,
        screen: ls
            .screen
            .as_ref()
            .map(|sc| crate::screen::score(sc, &ls.frames, start.original_frame)),
        stretches: None,
        together_frames: lockstep::together(ls).iter().filter(|t| **t).count() as u64,
        pairing: lockstep::pairing(&ls.frames),
        out_of_scope: ls.scope_end.map(|f| OutOfScope {
            original_frame: f,
            frame: f.saturating_sub(start.original_frame),
            frames: ls.out_of_scope,
        }),
        reads: None,
        stopped: false,
    }
}

fn number(s: &str) -> Option<Fx> {
    gp_model::Fixed::parse(s)
        .ok()
        .map(|f| Fx::from_raw(f.raw()))
}

/// The mechanic's short name: `platformer.jump` is "jump".
pub fn short(mechanic: &str) -> &str {
    mechanic.rsplit('.').next().unwrap_or(mechanic)
}

/// How the model is apart from the original at a split, in plain words.
pub fn apart(f: &FirstSplit) -> String {
    let field = f.path.rsplit('.').next().unwrap_or(&f.path);
    let owner = short(&f.mechanic);
    let when = if f.frame == 0 {
        "at the start, before any press".to_owned()
    } else {
        format!("from frame {}", f.frame)
    };
    let what = match (number(&f.original), number(&f.model)) {
        (Some(o), Some(m)) => {
            let d = Fx::from_raw((m.raw() - o.raw()).abs());
            let more = m > o;
            match field {
                "y" => format!(
                    "the model goes {d} px {}",
                    if more { "lower" } else { "higher" }
                ),
                "x" => format!(
                    "the model goes {d} px further {}",
                    if more { "right" } else { "left" }
                ),
                "vy" => format!(
                    "the model's vertical speed is {} (the original's {}), {d} px a frame more {}",
                    f.model,
                    f.original,
                    if more { "downward" } else { "upward" }
                ),
                "vx" => format!(
                    "the model's speed is {} (the original's {}), {d} px a frame more to the {}",
                    f.model,
                    f.original,
                    if more { "right" } else { "left" }
                ),
                _ => format!(
                    "the model's {field} is {}, the original's {}",
                    f.model, f.original
                ),
            }
        }
        _ if field == "on_ground" => {
            if f.model == "true" {
                "the model is on the ground and the original isn't".to_owned()
            } else {
                "the model leaves the ground and the original doesn't".to_owned()
            }
        }
        _ => format!(
            "the model's {field} is {}, the original's {}",
            f.model, f.original
        ),
    };
    format!("{what}, {when} ({owner})")
}

/// The lengths of a generated clip's sequences that hold a direction for
/// seconds ("Walk right 3 s"), beside the ladder's.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lengths {
    /// Seconds a walk or a run holds its direction, each one a sequence.
    pub seconds: Vec<u64>,
    /// The most frames a sequence runs, settle included: the clip cap.
    pub cap: u64,
}

impl Lengths {
    /// 1 and 3 seconds, capped at `cap_seconds` (8 by default) at `rate`.
    pub fn short(rate: (u64, u64), cap_seconds: u64) -> Self {
        Self {
            seconds: vec![1, 3],
            cap: frames_in(rate, cap_seconds),
        }
    }
}

/// Frames in `secs` seconds at `rate` (frames per second as a ratio).
pub fn frames_in(rate: (u64, u64), secs: u64) -> u64 {
    (secs * rate.0 + rate.1 / 2) / rate.1.max(1)
}

/// A generated clip's sequences: the ladder, and walks and runs that hold
/// the right direction for `lengths.seconds` each ("Walk right 3 s", "Run
/// right 3 s"), and a run then a jump. The walks are tier 3, since they
/// press a direction, and need what the ladder's do ([`link`]).
pub fn clip_sequences(model: &Model, catalog: &Catalog, lengths: &Lengths) -> Vec<Scenario> {
    let mut out = ladder(model, catalog);
    let Some(player) = player(model) else {
        return out;
    };
    let rate = (model.model.frame_rate.num, model.model.frame_rate.den);
    let acts = actions(model, catalog, &player);
    let mut b = Builder {
        model,
        catalog,
        player,
        out: Vec::new(),
        cap: lengths.cap,
    };
    let right = acts.iter().find(|a| a.button == "right");
    let run = acts.iter().find(|a| {
        !is_direction(&a.button)
            && a.mechanics.contains(&"platformer.run")
            && !a.mechanics.contains(&"platformer.jump")
    });
    let jump = acts
        .iter()
        .find(|a| !is_direction(&a.button) && a.mechanics.contains(&"platformer.jump"));
    let Some(r) = right else {
        return out;
    };
    let rm = r.mechanics.first().copied().unwrap_or("platformer.run");
    let longest = lengths.cap.saturating_sub(SETTLE);
    for &n in &lengths.seconds {
        let len = frames_in(rate, n).min(longest);
        b.add(
            3,
            format!("c.{}.walk{n}s", r.name),
            format!("Walk {} {n} s", r.name),
            rm,
            vec![span(&r.button, 0, len)],
        );
        if let Some(ra) = run {
            b.add(
                3,
                format!("c.{}+{}.{}{n}s", r.name, ra.name, ra.name),
                if ra.name == "run" {
                    format!("Run {} {n} s", r.name)
                } else {
                    format!("{} with {} held, {n} s", word(&r.name), ra.name)
                },
                "platformer.run",
                vec![span(&format!("{}+{}", r.button, ra.button), 0, len)],
            );
        }
    }
    if let Some(j) = jump {
        let len = frames_in(rate, 2).min(longest);
        let at = frames_in(rate, 1).min(len.saturating_sub(15));
        let (held, name) = match run {
            Some(ra) => (
                format!("{}+{}", r.button, ra.button),
                if ra.name == "run" {
                    format!("Run {} then jump", r.name)
                } else {
                    format!("{} with {} held, then jump", word(&r.name), ra.name)
                },
            ),
            None => (r.button.clone(), format!("Walk {} then jump", r.name)),
        };
        b.add(
            3,
            format!("c.{}.then_jump", r.name),
            name,
            "platformer.jump",
            vec![span(&held, 0, len), span(&j.button, at, 15)],
        );
    }
    out.extend(b.out);
    link(&mut out);
    out
}

/// A level in game words: "World 1-1" for a level whose HUD label is
/// "1-1", its label otherwise, and else the game's title when it has one
/// level, or the level's name in words. A label two levels share gets the
/// level's own words after it: "World 1-1 (underground)".
pub fn level_words(model: &Model, level: &str) -> String {
    let label = |id: &str| {
        model
            .levels
            .get(id)
            .and_then(|l| l.core.present.as_ref())
            .and_then(|p| p.label.clone())
    };
    let own = |id: &str| -> String {
        id.split('_')
            .filter(|w| {
                !w.is_empty()
                    && !w.chars().all(|c| c.is_ascii_digit())
                    && !(w.len() > 1
                        && w.starts_with('w')
                        && w[1..].chars().all(|c| c.is_ascii_digit()))
            })
            .collect::<Vec<_>>()
            .join(" ")
    };
    let Some(l) = label(level) else {
        return if model.levels.len() == 1 && !model.model.title.is_empty() {
            model.model.title.clone()
        } else {
            word(level)
        };
    };
    let world = |l: &str| {
        let numbered = l.split_once('-').is_some_and(|(a, b)| {
            !a.is_empty()
                && !b.is_empty()
                && a.chars()
                    .chain(b.chars())
                    .all(|c| c.is_ascii_alphanumeric())
        });
        if numbered {
            format!("World {l}")
        } else {
            l.to_owned()
        }
    };
    let shared = model
        .levels
        .keys()
        .any(|k| k != level && label(k).as_deref() == Some(l.as_str()));
    let words = own(level);
    if shared && !words.is_empty() {
        format!("{} ({words})", world(&l))
    } else {
        world(&l)
    }
}

/// A generated clip's name: "World 1-1: walk right 3 s".
pub fn clip_name(level: &str, sequence: &str) -> String {
    let mut c = sequence.chars();
    let s = match c.next() {
        Some(f) => f.to_lowercase().chain(c).collect::<String>(),
        None => String::new(),
    };
    format!("{level}: {s}")
}

/// A frame to start from that [`quiet_start`] found, and why.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Quiet {
    pub frame: u64,
    /// "Mario standing on the ground at 3.2 s, nothing near".
    pub says: String,
    /// Standing still (else only on the ground).
    pub still: bool,
}

/// How many frames the player must have stood before a quiet frame.
const STILL_FOR: u32 = 10;
/// Nothing within this many pixels of the player, left or right.
const NEAR: i64 = 80;

/// Finds a quiet frame of `inputs` at or after `after`: the player in the
/// level, on the ground and still for 10 frames, with no other living
/// entity within 80 px, by the mapped measures and the original's state translated. Failing
/// still, the first frame on the ground for 10 frames with nothing near.
/// `rate` is the model's frame rate, for the seconds in the sentence.
#[allow(clippy::too_many_arguments)]
pub fn quiet_start<O: Runtime>(
    original: &O,
    spec: &Spec,
    mapping: &Mapping,
    inputs: &[InputFrame],
    player: &str,
    after: u64,
    rate: (u64, u64),
) -> Result<Option<Quiet>, String> {
    let idx = |field: &str| {
        mapping
            .fields
            .iter()
            .position(|f| f.path == format!("entities.{player}[0].{field}"))
    };
    let (Some(ground), Some(x)) = (idx("on_ground"), idx("x")) else {
        return Ok(None);
    };
    let vx = idx("vx");
    let start = mapping
        .start
        .as_deref()
        .map(gp_runtime::select::Condition::parse)
        .transpose()?;
    let mut o = original.fork();
    let mut started = start.is_none();
    let mut still = 0u32;
    let mut grounded = 0u32;
    let mut last_x: Option<Value> = None;
    let mut fallback: Option<u64> = None;
    let player_kind = spec.kinds.index_of(player);
    let name = word(player);
    let secs = |f: u64| f as f64 * rate.1 as f64 / rate.0.max(1) as f64;
    let nothing_near = |o: &O| -> Result<bool, String> {
        let base = World::power_on(spec);
        let t = crate::translate::from_original(o, spec, &base, mapping)?;
        let Some(pk) = player_kind else {
            return Ok(true);
        };
        let Some(p) = t.world.bodies.iter().find(|b| b.kind == pk) else {
            return Ok(true);
        };
        // In the level: alive, and not above or below it (a game keeps a
        // player it is putting back off the screen).
        let rows = spec
            .levels
            .get(t.world.level)
            .map_or(i64::MAX, |l| l.size[1].saturating_mul(l.tile_size));
        if !p.alive || p.y < Fx::ZERO || (p.y.raw() >> 16) >= rows {
            return Ok(false);
        }
        Ok(!t.world.bodies.iter().any(|b| {
            b.kind != pk && b.alive && !b.waiting && ((b.x.raw() - p.x.raw()) >> 16).abs() < NEAR
        }))
    };
    for input in inputs {
        o.step(std::slice::from_ref(input))?;
        let f = o.frame();
        if !started {
            let cond = start.as_ref().expect("a start condition");
            started = cond.eval(&mut |sel| {
                o.query(&sel.to_string())?
                    .first()
                    .and_then(|e| e.value.as_int())
                    .ok_or(format!("{sel} names no number"))
            })?;
            if !started {
                continue;
            }
        }
        let v = crate::translate::read_original(&o, mapping)?;
        let on = matches!(v[ground], Value::Flag(true));
        let moving = vx.is_some_and(|i| v[i].as_int().is_some_and(|n| n != 0))
            || last_x.as_ref().is_some_and(|lx| *lx != v[x]);
        last_x = Some(v[x].clone());
        grounded = if on { grounded + 1 } else { 0 };
        still = if on && !moving { still + 1 } else { 0 };
        if f < after {
            continue;
        }
        if still >= STILL_FOR && nothing_near(&o)? {
            return Ok(Some(Quiet {
                frame: f,
                says: format!(
                    "{name} standing on the ground at {:.1} s, nothing near",
                    secs(f)
                ),
                still: true,
            }));
        }
        if fallback.is_none() && grounded >= STILL_FOR && nothing_near(&o)? {
            fallback = Some(f);
        }
    }
    Ok(fallback.map(|f| Quiet {
        frame: f,
        says: format!(
            "{name} on the ground at {:.1} s, nothing near (never standing still in this input, so the start is moving)",
            secs(f)
        ),
        still: false,
    }))
}

