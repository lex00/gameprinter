/// The scenario format's version.
pub const SCENARIO_VERSION: &str = "0.4.0";

/// Frames with nothing pressed after a scenario's last press, so a jump
/// lands and a run slows down before the measuring stops.
pub const SETTLE: u64 = 40;

/// The most frames a generated scenario runs: about 2 seconds.
pub const MAX_FRAMES: u64 = 120;

/// Where a scenario starts: the original's frame of an input, or an
/// emulator snapshot taken there. The input is the ladder's own unless
/// `log` names an input log file of its own, such as a free play save
/// point's (docs/show.md, "Free play"): the frames from power-on that
/// reach the start.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StartAt {
    /// The input the original plays to the frame: a recording's ID, a
    /// baseline file or a capture run's recording name.
    pub input: String,
    /// The original's frame.
    pub frame: u64,
    /// An emulator snapshot of the original at the frame, by the file or
    /// hash its owner keeps it under, when there is one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub snapshot: Option<String>,
    /// An input log file the original plays from power-on to the frame,
    /// in place of the ladder's input: a path relative to `$GP_HOME`, or
    /// absolute. Its owner keeps it unchanged.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub log: Option<String>,
    /// The model's frame at the start, as the lockstep counts it, for a
    /// start taken from `snapshot` without playing the input to it (a
    /// generated clip's, [`crate::starts`]).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub model_frame: Option<u64>,
}

/// Where a scenario came from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "lowercase")]
pub enum Source {
    /// Generated by [`ladder`] from the model's actions and mechanics.
    Generated,
    /// Played by a person from the start, recorded frame by frame.
    Played {
        /// When, as the page or the command gives it (an ISO date).
        when: String,
        by: String,
    },
}

/// A number of the mechanic a scenario is about, as the model sets it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ParamValue {
    pub path: String,
    pub value: String,
}

/// One scenario.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Scenario {
    /// Stable for the same model: `t1.jump.hold15`.
    pub id: String,
    /// In plain words: "Jump, held 15 frames".
    pub name: String,
    /// 1 to 3 for a generated scenario, 0 for a played one.
    pub tier: u8,
    /// The mechanic it is about, as the catalog names it, or empty.
    #[serde(default)]
    pub mechanic: String,
    #[serde(default)]
    pub params: Vec<ParamValue>,
    /// Frames it runs, presses and settle.
    pub frames: u64,
    /// Its presses as button spans (`a@0-14`, `right+b@0-59`), frames
    /// counted from the start; empty with `log`.
    #[serde(default)]
    pub presses: Vec<String>,
    /// Its presses as an input log (gp-input-log text), for a played one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub log: Option<String>,
    /// The scenarios that must pass before this one opens, by ID: for a
    /// generated one, the scenarios of each of its buttons alone
    /// ([`link`]); for a played one, those of the mechanics it moves
    /// ([`played_requires`]).
    #[serde(default)]
    pub requires: Vec<String>,
    /// The start, for a scenario that carries its own; a generated one
    /// takes the ladder's.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start: Option<StartAt>,
    pub source: Source,
}

impl Scenario {
    /// Its presses, a frame each.
    pub fn inputs(&self) -> Result<Vec<InputFrame>, String> {
        let log = match &self.log {
            Some(text) => input_log::InputLog::parse(text).map_err(|e| e.to_string())?,
            None => {
                let spans: Vec<&str> = self.presses.iter().map(String::as_str).collect();
                let n = usize::try_from(self.frames).unwrap_or(usize::MAX);
                input_log::generate(n, &spans).map_err(|e| e.to_string())?
            }
        };
        Ok(log
            .frames
            .iter()
            .map(|f| InputFrame {
                buttons: f.buttons_word(),
                axes: Vec::new(),
                reset: f.reset,
            })
            .collect())
    }

    /// Its presses as an input log's text, the store's format.
    pub fn log_text(&self) -> Result<String, String> {
        if let Some(t) = &self.log {
            return Ok(t.clone());
        }
        let spans: Vec<&str> = self.presses.iter().map(String::as_str).collect();
        let n = usize::try_from(self.frames).unwrap_or(usize::MAX);
        Ok(input_log::generate(n, &spans)
            .map_err(|e| e.to_string())?
            .to_text())
    }
}

/// An action the model binds to a button, and the mechanics of the player
/// that read it.
#[derive(Debug, Clone)]
struct Action {
    name: String,
    button: String,
    mechanics: Vec<&'static str>,
}

fn is_direction(button: &str) -> bool {
    matches!(button, "left" | "right" | "up" | "down")
}

/// The player's entity name: the first with role `player`.
pub fn player(model: &Model) -> Option<String> {
    let tree = model.to_tree();
    tree.get("entities")?
        .as_table()?
        .iter()
        .find(|(_, e)| e.get("role").and_then(|r| r.as_str()) == Some("player"))
        .map(|(k, _)| k.clone())
}

fn table_at<'a>(tree: &'a toml::Value, path: &str) -> Option<&'a toml::Value> {
    let mut node = tree;
    for part in path.split('.') {
        node = node.get(part)?;
    }
    Some(node)
}

/// The table a mechanic's parameters are in, for one of its uses: the
/// component's own table, or beside a field such as `tile_collision`.
fn params_table<'a>(tree: &'a toml::Value, used_by: &str) -> Option<(String, &'a toml::Value)> {
    match table_at(tree, used_by) {
        Some(t @ toml::Value::Table(_)) => Some((used_by.to_owned(), t)),
        _ => {
            let (base, _) = used_by.rsplit_once('.')?;
            Some((base.to_owned(), table_at(tree, base)?))
        }
    }
}

/// The player's mechanics, each with the table its parameters are in.
fn player_mechanics<'a>(
    catalog: &'a Catalog,
    tree: &'a toml::Value,
    player: &str,
) -> Vec<(&'a crate::mechanics::Mechanic, String, &'a toml::Value)> {
    let part = format!("entities.{player}.");
    let mut out = Vec::new();
    for m in &catalog.mechanics {
        for u in &m.used_by {
            if (u.starts_with(&part) || *u == part.trim_end_matches('.'))
                && let Some((base, t)) = params_table(tree, u)
            {
                out.push((m, base, t));
                break;
            }
        }
    }
    out
}

fn actions(model: &Model, catalog: &Catalog, player: &str) -> Vec<Action> {
    let tree = model.to_tree();
    let Some(table) = tree
        .get("input")
        .and_then(|i| i.get("actions"))
        .and_then(|a| a.as_table())
    else {
        return Vec::new();
    };
    let mechs = player_mechanics(catalog, &tree, player);
    let mut out: Vec<Action> = Vec::new();
    for (name, button) in table {
        let Some(button) = button.as_str() else {
            continue;
        };
        let mut mechanics = Vec::new();
        for (m, _, t) in &mechs {
            // An action parameter set to it, or one left out whose name is
            // the action's (a component's default), or a read of it.
            let by_param = m.params.iter().any(|p| {
                p.ty == "action"
                    && match t.get(p.name).and_then(|v| v.as_str()) {
                        Some(v) => v == name,
                        None => p.name == name,
                    }
            });
            let reads = m.reads.iter().any(|r| *r == format!("action.{name}"));
            if (by_param || reads) && !mechanics.contains(&m.name) {
                mechanics.push(m.name);
            }
        }
        out.push(Action {
            name: name.clone(),
            button: button.to_ascii_lowercase(),
            mechanics,
        });
    }
    // One action a button: the first the model lists.
    let mut seen = std::collections::BTreeSet::new();
    out.retain(|a| seen.insert(a.button.clone()));
    out
}

/// The numbers a mechanic's use by the player sets, for a scenario's
/// `params`.
fn params_of(catalog: &Catalog, model: &Model, player: &str, mechanic: &str) -> Vec<ParamValue> {
    let tree = model.to_tree();
    let Some((m, base, t)) = player_mechanics(catalog, &tree, player)
        .into_iter()
        .find(|(m, ..)| m.name == mechanic)
    else {
        return Vec::new();
    };
    let mut out = Vec::new();
    for p in &m.params {
        if !matches!(p.ty, "fixed" | "frames" | "count" | "bool") {
            continue;
        }
        if let Some(v) = t.get(p.name) {
            let value = match v {
                toml::Value::String(s) => s.clone(),
                other => other.to_string(),
            };
            out.push(ParamValue {
                path: format!("{base}.{}", p.name),
                value,
            });
        }
    }
    out
}

/// A fixed-point parameter of the player's mechanic, if the model sets it.
fn fixed_param(
    model: &Model,
    catalog: &Catalog,
    player: &str,
    mechanic: &str,
    name: &str,
) -> Option<Fx> {
    let tree = model.to_tree();
    let (_, _, t) = player_mechanics(catalog, &tree, player)
        .into_iter()
        .find(|(m, ..)| m.name == mechanic)?;
    match t.get(name)? {
        toml::Value::Integer(i) => Some(Fx::from_raw(i.checked_mul(1 << 16)?)),
        toml::Value::String(s) => gp_model::Fixed::parse(s)
            .ok()
            .map(|f| Fx::from_raw(f.raw())),
        _ => None,
    }
}

/// An action's name in plain words: `jump` is "Jump".
fn word(name: &str) -> String {
    let mut c = name.chars();
    match c.next() {
        Some(f) => f
            .to_uppercase()
            .chain(c)
            .collect::<String>()
            .replace('_', " "),
        None => String::new(),
    }
}

struct Builder<'a> {
    model: &'a Model,
    catalog: &'a Catalog,
    player: String,
    out: Vec<Scenario>,
    /// The most frames one runs.
    cap: u64,
}

impl Builder<'_> {
    fn add(&mut self, tier: u8, id: String, name: String, mechanic: &str, presses: Vec<String>) {
        if self.out.iter().any(|s| s.id == id) {
            return;
        }
        let last = presses
            .iter()
            .filter_map(|p| {
                p.rsplit_once('-')
                    .and_then(|(_, to)| to.parse::<u64>().ok())
            })
            .max()
            .unwrap_or(0);
        let frames = if presses.is_empty() {
            60
        } else {
            (last + 1 + SETTLE).min(self.cap)
        };
        self.out.push(Scenario {
            id,
            name,
            tier,
            mechanic: mechanic.to_owned(),
            params: if mechanic.is_empty() {
                Vec::new()
            } else {
                params_of(self.catalog, self.model, &self.player, mechanic)
            },
            frames,
            presses,
            requires: Vec::new(),
            log: None,
            start: None,
            source: Source::Generated,
        });
    }
}

fn span(button: &str, from: u64, len: u64) -> String {
    format!("{button}@{from}-{}", from + len.max(1) - 1)
}

/// The scenarios for `model`, generated from its input actions and its
/// mechanic catalog, tier 1 first. A model without a player gets none.
pub fn ladder(model: &Model, catalog: &Catalog) -> Vec<Scenario> {
    let Some(player) = player(model) else {
        return Vec::new();
    };
    let acts = actions(model, catalog, &player);
    let mut b = Builder {
        model,
        catalog,
        player: player.clone(),
        out: Vec::new(),
        cap: MAX_FRAMES,
    };
    let mech = |a: &Action| a.mechanics.first().copied().unwrap_or("");
    let buttons: Vec<&Action> = acts.iter().filter(|a| !is_direction(&a.button)).collect();
    let dirs: Vec<&Action> = acts.iter().filter(|a| is_direction(&a.button)).collect();

    // Tier 1: each button alone.
    b.add(
        1,
        "t1.nothing".into(),
        "Nothing pressed for 60 frames".into(),
        "",
        Vec::new(),
    );
    for a in &buttons {
        let w = word(&a.name);
        let m = mech(a);
        b.add(
            1,
            format!("t1.{}.tap", a.name),
            format!("{w}, tapped for 1 frame"),
            m,
            vec![span(&a.button, 0, 1)],
        );
        for n in [5, 15, 30] {
            b.add(
                1,
                format!("t1.{}.hold{n}", a.name),
                format!("{w}, held {n} frames"),
                m,
                vec![span(&a.button, 0, n)],
            );
        }
        b.add(
            1,
            format!("t1.{}.twice", a.name),
            format!("{w}, tapped, released for 5 frames, tapped again"),
            m,
            vec![span(&a.button, 0, 1), span(&a.button, 6, 1)],
        );
    }

    // Tier 2: what the mechanics say combine.
    let jump = buttons
        .iter()
        .find(|a| a.mechanics.contains(&"platformer.jump"))
        .copied();
    let run_action = buttons.iter().find(|a| {
        a.mechanics.contains(&"platformer.run") && !a.mechanics.contains(&"platformer.jump")
    });
    if let Some(j) = jump {
        let m = "platformer.jump";
        // How long a tapped jump is in the air, from its numbers: twice its
        // speed over its gravity. Only to place a press near the landing.
        let speed = fixed_param(model, catalog, &player, m, "speed").map(|s| s.raw().abs());
        let gravity = fixed_param(model, catalog, &player, m, "gravity").map(|g| g.raw());
        let air = match (speed, gravity) {
            (Some(s), Some(g)) if g > 0 => u64::try_from(2 * s / g).unwrap_or(30).clamp(8, 60),
            _ => 30,
        };
        // Whether any of the player's mechanics jumps in the air.
        let tree = model.to_tree();
        let double = player_mechanics(catalog, &tree, &player)
            .iter()
            .any(|(m, _, t)| {
                m.name.contains("double")
                    || m.params.iter().any(|p| {
                        (p.name.contains("air_jump") || p.name.contains("double"))
                            && t.get(p.name).is_some()
                    })
            });
        b.add(
            2,
            "t2.jump.again_in_air".into(),
            if double {
                "Jump, then jump again in the air (a double jump)".into()
            } else {
                "Jump, then press jump again in the air (the model has no double jump)".into()
            },
            m,
            vec![span(&j.button, 0, 5), span(&j.button, air / 3 + 5, 5)],
        );
        b.add(
            2,
            "t2.jump.held_through_landing".into(),
            "Jump, held through the landing".into(),
            m,
            vec![span(&j.button, 0, (air + 15).min(MAX_FRAMES - SETTLE))],
        );
        b.add(
            2,
            "t2.jump.again_on_landing".into(),
            "Jump, then jump again as it lands".into(),
            m,
            vec![span(&j.button, 0, 1), span(&j.button, air + 2, 5)],
        );
        if fixed_param(model, catalog, &player, m, "buffer_frames").is_some() {
            b.add(
                2,
                "t2.jump.just_before_landing".into(),
                "Jump, then jump pressed just before it lands".into(),
                m,
                vec![
                    span(&j.button, 0, 1),
                    span(&j.button, air.saturating_sub(3), 5),
                ],
            );
        }
        if let Some(r) = run_action {
            let rw = word(&r.name);
            b.add(
                2,
                format!("t2.{}.then_jump", r.name),
                format!("{rw} held, then jump"),
                "platformer.run",
                vec![span(&r.button, 0, 40), span(&j.button, 10, 15)],
            );
            b.add(
                2,
                format!("t2.jump.then_{}", r.name),
                format!("Jump, then {} pressed in the air", r.name),
                m,
                vec![span(&j.button, 0, 15), span(&r.button, 5, 20)],
            );
        }
        for o in &buttons {
            if o.button == j.button || run_action.is_some_and(|r| r.button == o.button) {
                continue;
            }
            b.add(
                2,
                format!("t2.jump.then_{}", o.name),
                format!("Jump, then {} in the air", o.name),
                mech(o),
                vec![span(&j.button, 0, 5), span(&o.button, 8, 5)],
            );
        }
    }
    for (i, x) in buttons.iter().enumerate() {
        for y in &buttons[i + 1..] {
            b.add(
                2,
                format!("t2.{}+{}", x.name, y.name),
                format!("{} and {} together, held 15 frames", word(&x.name), y.name),
                mech(x),
                vec![span(&format!("{}+{}", x.button, y.button), 0, 15)],
            );
        }
    }

    // Tier 3: with directions.
    let side: Vec<&&Action> = dirs
        .iter()
        .filter(|d| matches!(d.button.as_str(), "left" | "right"))
        .collect();
    for d in &side {
        let w = word(&d.name);
        let m = mech(d);
        b.add(
            3,
            format!("t3.{}.tap", d.name),
            format!("{w}, tapped for 1 frame"),
            m,
            vec![span(&d.button, 0, 1)],
        );
        b.add(
            3,
            format!("t3.{}.hold15", d.name),
            format!("{w}, held 15 frames"),
            m,
            vec![span(&d.button, 0, 15)],
        );
        b.add(
            3,
            format!("t3.{}.hold60", d.name),
            format!("{w}, held 60 frames"),
            m,
            vec![span(&d.button, 0, 60)],
        );
        if let Some(r) = run_action {
            b.add(
                3,
                format!("t3.{}+{}", d.name, r.name),
                format!("{w} with {} held, 60 frames", r.name),
                "platformer.run",
                vec![span(&format!("{}+{}", d.button, r.button), 0, 60)],
            );
        }
    }
    if let (Some(r), Some(l)) = (
        side.iter().find(|d| d.button == "right"),
        side.iter().find(|d| d.button == "left"),
    ) {
        b.add(
            3,
            format!("t3.{}.then_{}", r.name, l.name),
            format!("{}, held 30 frames, then {} for 30", word(&r.name), l.name),
            mech(r),
            vec![span(&r.button, 0, 30), span(&l.button, 30, 30)],
        );
        if let Some(j) = jump {
            for at in [0, 10, 30] {
                b.add(
                    3,
                    format!("t3.{}.jump_at{at}", r.name),
                    format!("{} held, jump at frame {at}", word(&r.name)),
                    "platformer.jump",
                    vec![span(&r.button, 0, 60), span(&j.button, at, 15)],
                );
            }
            if let Some(ra) = run_action {
                b.add(
                    3,
                    format!("t3.{}+{}.jump", r.name, ra.name),
                    format!("{} with {} held, jump at frame 30", word(&r.name), ra.name),
                    "platformer.jump",
                    vec![
                        span(&format!("{}+{}", r.button, ra.button), 0, 60),
                        span(&j.button, 30, 15),
                    ],
                );
            }
            b.add(
                3,
                "t3.jump.turn_in_air".into(),
                format!(
                    "{} and jump, then turn {} in the air",
                    word(&r.name),
                    l.name
                ),
                "platformer.run",
                vec![
                    span(&r.button, 0, 20),
                    span(&j.button, 5, 15),
                    span(&l.button, 20, 20),
                ],
            );
            b.add(
                3,
                "t3.jump.then_right".into(),
                format!("Jump straight up, then {} in the air", r.name),
                "platformer.run",
                vec![span(&j.button, 0, 15), span(&r.button, 5, 30)],
            );
        }
    }
    for d in dirs
        .iter()
        .filter(|d| matches!(d.button.as_str(), "up" | "down"))
    {
        // Up and down only for a mechanic that reads them (a crouch, a
        // climb, a door).
        if d.mechanics.is_empty() {
            continue;
        }
        let w = word(&d.name);
        b.add(
            3,
            format!("t3.{}.hold30", d.name),
            format!("{w}, held 30 frames"),
            mech(d),
            vec![span(&d.button, 0, 30)],
        );
        if let Some(r) = side.iter().find(|s| s.button == "right") {
            b.add(
                3,
                format!("t3.{}.while_{}", d.name, r.name),
                format!("{} held, then {w} for 20 frames", word(&r.name)),
                mech(d),
                vec![span(&r.button, 0, 40), span(&d.button, 20, 20)],
            );
        }
    }
    let mut out = b.out;
    link(&mut out);
    out
}

/// The buttons a scenario presses, from its spans.
fn buttons_of(s: &Scenario) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for p in &s.presses {
        let Some((bs, _)) = p.split_once('@') else {
            continue;
        };
        for b in bs.split('+') {
            if !out.iter().any(|x| x == b) {
                out.push(b.to_owned());
            }
        }
    }
    out
}

/// Fills each generated scenario's `requires`: one that presses a single
/// button needs nothing pressed to match first (the start); any other needs
/// every scenario that presses each of its buttons alone: a combination
/// needs each button's tier-1 scenarios, a direction with a button needs
/// the direction alone and the button's.
pub fn link(ladder: &mut [Scenario]) {
    let alone: Vec<(String, String)> = ladder
        .iter()
        .filter_map(|s| match buttons_of(s).as_slice() {
            [b] => Some((b.clone(), s.id.clone())),
            _ => None,
        })
        .collect();
    let nothing = ladder
        .iter()
        .find(|s| s.presses.is_empty() && s.source == Source::Generated)
        .map(|s| s.id.clone());
    for s in ladder.iter_mut() {
        if s.source != Source::Generated || s.presses.is_empty() {
            continue;
        }
        let bs = buttons_of(s);
        s.requires = if bs.len() == 1 {
            nothing.iter().cloned().collect()
        } else {
            alone
                .iter()
                .filter(|(b, id)| bs.contains(b) && *id != s.id)
                .map(|(_, id)| id.clone())
                .collect()
        };
    }
}

/// What a played scenario needs first: the tier-1 scenarios about the
/// mechanics whose measures the original moved in it (`moved`, from its
/// [`Outcome`]). It can still be opened by hand.
pub fn played_requires(ladder: &[Scenario], moved: &[String]) -> Vec<String> {
    ladder
        .iter()
        .filter(|s| s.tier == 1 && !s.mechanic.is_empty() && moved.contains(&s.mechanic))
        .map(|s| s.id.clone())
        .collect()
}

/// When a scenario passes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(tag = "bar", rename_all = "lowercase")]
pub enum Bar {
    /// Exact on every measure the mapping covers: no split.
    #[default]
    Exact,
    /// At least this share of every measure's frames within its tolerance,
    /// in tenths of a percent (1000 is every frame).
    Together { permille: u64 },
}

impl Bar {
    pub fn passes(self, o: &Outcome) -> bool {
        match self {
            Self::Exact => o.exact,
            Self::Together { permille } => o.headline.together_permille >= permille,
        }
    }

    /// `exact`, or a share of frames together: `99%`, `99.5%`.
    pub fn parse(s: &str) -> Result<Self, String> {
        if s == "exact" {
            return Ok(Self::Exact);
        }
        let pct: f64 = s.trim_end_matches('%').parse().map_err(|_| {
            format!("a bar is `exact` or a share of frames together such as 99%, not `{s}`")
        })?;
        if !(0.0..=100.0).contains(&pct) {
            return Err(format!("{s} isn't a share from 0% to 100%"));
        }
        Ok(Self::Together {
            permille: (pct * 10.0).round() as u64,
        })
    }

    pub fn says(self) -> String {
        match self {
            Self::Exact => "exact on every measure".into(),
            Self::Together { permille } => {
                format!("{}% of frames together", permille as f64 / 10.0)
            }
        }
    }
}

/// Where a scenario stands.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum State {
    /// Something it needs doesn't pass yet.
    Locked,
    /// Everything it needs passes, and it hasn't been run.
    Open,
    Failing,
    Passed,
}

/// Each scenario's state, in ladder order, from the results so far
/// (`None` for one not run). `opened` are opened by hand whatever they
/// need.
pub fn states(
    ladder: &[Scenario],
    results: &[Option<&Outcome>],
    bar: Bar,
    opened: &[String],
) -> Vec<State> {
    let passed = |id: &str| {
        ladder
            .iter()
            .position(|s| s.id == id)
            .and_then(|i| results.get(i).copied().flatten())
            .is_some_and(|o| bar.passes(o))
    };
    ladder
        .iter()
        .enumerate()
        .map(|(i, s)| {
            let r = results.get(i).copied().flatten();
            if r.is_some_and(|o| bar.passes(o)) {
                State::Passed
            } else if !opened.contains(&s.id) && !s.requires.iter().all(|q| passed(q)) {
                State::Locked
            } else if r.is_some() {
                State::Failing
            } else {
                State::Open
            }
        })
        .collect()
}

/// The next scenario to work on: the first in ladder order that is open
/// or failing.
pub fn next(states: &[State]) -> Option<usize> {
    states
        .iter()
        .position(|s| matches!(s, State::Open | State::Failing))
}

/// The scenarios a scenario unlocks: those that need it.
pub fn unlocks<'a>(ladder: &'a [Scenario], id: &str) -> Vec<&'a Scenario> {
    ladder
        .iter()
        .filter(|s| s.requires.iter().any(|r| r == id))
        .collect()
}

/// "needs: Jump, tapped for 1 frame; Right, held 60 frames" and
/// "unlocks: ...", in plain words, for the ones not passed.
pub fn needs_says(ladder: &[Scenario], s: &Scenario, states: &[State]) -> String {
    let names: Vec<&str> = s
        .requires
        .iter()
        .filter_map(|r| ladder.iter().position(|x| x.id == *r))
        .filter(|&i| states.get(i) != Some(&State::Passed))
        .map(|i| ladder[i].name.as_str())
        .collect();
    if names.is_empty() {
        String::new()
    } else {
        format!("needs: {}", names.join("; "))
    }
}

