//! Scenarios (docs/interpreter.md, "Scenarios: one press at a time"): a
//! few frames of presses, run on the original and on the model from the
//! same start, the original's state at one of its frames, and measured
//! apart with the lockstep.
//!
//! A scenario is its start, its presses (an input log in the store's
//! format), and where it came from: `generated` from the model's input
//! actions and mechanic catalog, with its tier and the mechanic it is
//! about, or `played` by a person from that start. Both kinds run the same
//! way: the original stands at the start's frame, the model loads the
//! original's state there translated ([`crate::translate`]), and both take
//! the same presses ([`crate::lockstep::lockstep_from`]).
//!
//! [`ladder`] generates the scenarios for any model, in tiers:
//!
//! | Tier | What |
//! |---|---|
//! | 1 | Each button that isn't a direction, alone: tapped, held 5, 15 and 30 frames, tapped twice; and nothing pressed |
//! | 2 | Combinations the mechanics say exist: a second jump in the air (which a model without a double jump says does nothing), a jump held through the landing, a jump again on landing, the run button with the jump, two buttons together |
//! | 3 | With directions: each alone, the run button with one, a jump at several timings while walking, a turn in the air, up and down when a mechanic reads them |
//!
//! [`quiet_start`] finds a frame of a recording to start from: the player
//! on the ground, still, with nothing near.

use serde::{Deserialize, Serialize};

use gp_evidence::input_log;
use gp_model::Model;
use gp_runtime::{InputFrame, Runtime, Value};
use gp_sim::{Fx, Spec, World};

use crate::lockstep::{self, Lockstep, Mode, Options, Start};
