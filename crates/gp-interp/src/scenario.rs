/// A value's name, for a measure of names; empty for a number.
fn name_text(v: &Value) -> String {
    match v {
        Value::Text(t) => t.clone(),
        _ => String::new(),
    }
}

/// A value as a curve's number in text, empty for a name.
fn curve_text(v: &Value) -> String {
    curve_value(v).map_or(String::new(), |x| x.to_string())
}

/// A value as a number for a curve: flags are 0 or 1, a name has none.
pub fn curve_value(v: &Value) -> Option<f64> {
    match v {
        Value::Fixed(r) => Some(*r as f64 / 65536.0),
        Value::Int(n) => Some(*n as f64),
        Value::Flag(b) => Some(f64::from(u8::from(*b))),
        Value::Entity(n) => Some(*n as f64),
        _ => None,
    }
}

