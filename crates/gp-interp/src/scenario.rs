/// A body's turn or change in one game.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BodyEvent {
    /// Frames from the start.
    pub frame: u64,
    /// `original` or `model`.
    pub game: String,
    pub what: String,
}

/// Each body's score in `ls`, from the original's frame `start` on.
pub fn bodies(ls: &Lockstep, start: u64) -> Vec<BodyScore> {
    let frame = |at: usize| ls.frames.get(at).map_or(0, |f| f.1.saturating_sub(start));
    ls.bodies
        .iter()
        .map(|b| {
            let kind = b.kind.replace('_', " ");
            let (first, first_frame, says) = match b.one_sided() {
                Some(side) => {
                    let other = if side == "original" {
                        "model"
                    } else {
                        "original"
                    };
                    let s = format!("the {side} has a {kind} the {other} doesn't");
                    (Some(s.clone()), Some(frame(b.from)), s)
                }
                None => match crate::bodies::mismatches(b).first() {
                    Some(m) => {
                        let (short, long) = mismatch_words(&b.name(), &kind, m, &frame);
                        (Some(short), Some(frame(m.at())), long)
                    }
                    None => (None, None, "the same in both".into()),
                },
            };
            BodyScore {
                kind: b.kind.clone(),
                name: b.name(),
                paired: b.mapped || b.paired.is_some(),
                side: b.one_sided().unwrap_or("both").into(),
                from: frame(b.from),
                paths: b.paths.iter().map(|&i| ls.paths[i].path.clone()).collect(),
                events: b
                    .events
                    .iter()
                    .map(|e| BodyEvent {
                        frame: frame(e.at),
                        game: if e.original { "original" } else { "model" }.into(),
                        what: e.what.clone(),
                    })
                    .collect(),
                first,
                first_frame,
                says,
            }
        })
        .collect()
}

/// A mismatch in words, short ("the second goomba turns left 4 frames
/// late") and long ("the original's goomba turns left at frame 40, the
/// model's at 44").
fn mismatch_words(
    name: &str,
    kind: &str,
    m: &crate::bodies::Mismatch,
    frame: &dyn Fn(usize) -> u64,
) -> (String, String) {
    let w = &m.what;
    match (m.original, m.model) {
        (Some(a), Some(b)) => {
            let (fa, fb) = (frame(a), frame(b));
            let n = fa.abs_diff(fb);
            let when = if fb > fa { "late" } else { "early" };
            let frames = if n == 1 { "frame" } else { "frames" };
            (
                format!("{name} {w} {n} {frames} {when}"),
                format!("the original's {kind} {w} at frame {fa}, the model's at {fb}"),
            )
        }
        (Some(a), None) => (
            format!("{name} {w} in the original only"),
            format!(
                "the original's {kind} {w} at frame {}, the model's doesn't",
                frame(a)
            ),
        ),
        (None, Some(b)) => (
            format!("{name} {w} in the model only"),
            format!(
                "the model's {kind} {w} at frame {}, the original's doesn't",
                frame(b)
            ),
        ),
        (None, None) => (String::new(), String::new()),
    }
}

/// Where one track first goes wrong in a scenario: "Mario: wrong from
/// frame 1".
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TrackFirst {
    /// The entity kind, `camera` or `game`.
    pub track: String,
    /// Frames from the start.
    pub frame: u64,
    pub original_frame: u64,
    /// The measure wrong there (the first of them), both values and the
    /// measure in words.
    pub path: String,
    pub original: String,
    pub model: String,
    pub words: String,
    /// For a body's track, why in words, from its events: "the second
    /// goomba turns left 4 frames late", "the original has a goomba the
    /// model doesn't".
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
    /// "Mario: wrong from frame 1 (Mario's speed across, original 0.0625,
    /// rebuilt 0.037109375)", "Goomba: wrong from frame 40 (the goomba
    /// turns left 4 frames late)".
    pub says: String,
}

/// Each track's first wrong frame in `ls`, from the original's frame
/// `start` on: the bodies by frame, then the camera.
pub fn tracks(ls: &Lockstep, start: u64) -> Vec<TrackFirst> {
    let mut out: Vec<TrackFirst> = Vec::new();
    for (i, p) in ls.paths.iter().enumerate() {
        let Some(k) = p.distance.iter().position(|d| *d > p.tolerance) else {
            continue;
        };
        let of = ls.frames[k].1;
        let t = lockstep::track(&p.path);
        if out.iter().any(|x| x.track == t && x.original_frame <= of) {
            continue;
        }
        out.retain(|x| x.track != t);
        let (original, model) = ls
            .values
            .get(k)
            .map_or((String::new(), String::new()), |(o, m)| {
                (show(&o[i]), show(&m[i]))
            });
        let frame = of.saturating_sub(start);
        let words = lockstep::words(&p.path);
        let name = if t == "camera" || t == "game" {
            t.clone()
        } else {
            let words = t.replace('_', " ");
            let mut c = words.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect())
                .unwrap_or_default()
        };
        // A body's events say why, when they part on or before this frame.
        let reason = ls
            .bodies
            .iter()
            .find(|b| b.paths.contains(&i))
            .and_then(|b| {
                let kind = b.kind.replace('_', " ");
                if let Some(side) = b.one_sided() {
                    let other = if side == "original" {
                        "model"
                    } else {
                        "original"
                    };
                    return Some(format!("the {side} has a {kind} the {other} doesn't"));
                }
                let at = |a: usize| ls.frames.get(a).map_or(0, |f| f.1.saturating_sub(start));
                crate::bodies::mismatches(b)
                    .into_iter()
                    .find(|m| m.at() <= k)
                    .map(|m| mismatch_words(&b.name(), &kind, &m, &at).0)
            });
        let says = if let Some(r) = &reason {
            format!("{name}: wrong from frame {frame} ({r})")
        } else if original.is_empty() {
            format!("{name}: wrong from frame {frame} ({words})")
        } else {
            format!(
                "{name}: wrong from frame {frame} ({words}, original {original}, rebuilt {model})"
            )
        };
        out.push(TrackFirst {
            track: t,
            frame,
            original_frame: of,
            path: p.path.clone(),
            original,
            model,
            words,
            reason,
            says,
        });
    }
    out.sort_by_key(|x| (x.track == "camera", x.original_frame, x.track.clone()));
    out
}

