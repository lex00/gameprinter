//! The slot catalog (docs/stubs.md): a record per asset slot for the
//! agents that fill and replace them. A record has two halves. The
//! specification (kind, role, shape, the entities that draw from the slot,
//! whether the simulation reads it, the contract level, the checks a
//! replacement must pass) is worked out from the model, the contract and
//! the asset map whenever it's asked for, so it can't go stale and holds
//! no game data. The state (status and provenance) belongs to one set of
//! assets and is kept beside them in `slots.toml`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use gp_assets::{Asset, AssetMap};
use gp_contract::Contract;
use gp_model::Model;
use gp_model::model::AssetKind;
use gp_model::path::Step;
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

/// The state file's name, in a directory of assets in the lifted format.
pub const STATE_FILE: &str = "slots.toml";

/// The state file's format version.
pub const FORMAT: &str = "0.1.0";

/// The license stub assets carry (decided by the user, 2026-10-28): they
/// hold no creative work, so any fork may keep them.
pub const STUB_LICENSE: &str = "CC0-1.0";

/// The license recorded for an original asset of a commercial-tier
/// template: it comes from the person's own copy and is never shared.
pub const OWN_COPY_LICENSE: &str = "LicenseRef-own-copy";

/// The status the catalog reports for a slot whose files no longer match
/// the digest `slots.toml` records for them. It's never stored.
pub const MODIFIED: &str = "modified";

/// The license recorded for an original asset of an open-tier template:
/// the template source's own terms.
pub const TEMPLATE_LICENSE: &str = "LicenseRef-template-source";

/// What fills a slot now.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "kebab-case")]
pub enum Status {
    /// Lifted from the source.
    Original,
    /// A placeholder of the same shape (`gp assets stub`).
    Stub,
    /// Placed by `assets_place`.
    Replaced,
}

impl Status {
    pub fn name(self) -> &'static str {
        match self {
            Status::Original => "original",
            Status::Stub => "stub",
            Status::Replaced => "replaced",
        }
    }
}

/// Where a slot's current files came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "kebab-case")]
pub enum Origin {
    /// The source game, through the asset map.
    Source,
    /// Generated by `gp assets stub`.
    Stub,
    /// Made by a generator (a model or a tool).
    Generated,
    /// Supplied by a person.
    Uploaded,
}

/// One slot's state.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct SlotState {
    pub status: Status,
    pub origin: Origin,
    /// An SPDX license expression, or `LicenseRef-own-copy` for an
    /// original extracted from the person's own copy.
    pub license: String,
    /// The SHA-256 of the slot's files, as `sha256sum` lines sorted by
    /// name and hashed again (the template manifest's `lifted_sha256`).
    pub sha256: String,
    /// The tool or model that made it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub generator: Option<String>,
    /// Who made it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub author: Option<String>,
    /// One line on what it is or why it was placed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

/// The state file: every slot's state, by slot name.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct State {
    /// The format version, 0.1.0.
    pub format: String,
    /// The model the slots are its.
    pub model: String,
    #[serde(default)]
    pub slots: BTreeMap<String, SlotState>,
}

impl State {
    pub fn new(model: &str) -> Self {
        Self {
            format: FORMAT.into(),
            model: model.into(),
            slots: BTreeMap::new(),
        }
    }

    pub fn parse(text: &str) -> Result<Self, String> {
        let s: State = toml::from_str(text).map_err(|e| format!("{STATE_FILE}: {e}"))?;
        if s.format != FORMAT {
            return Err(format!(
                "{STATE_FILE}: format {} isn't {FORMAT}, the one this gp reads",
                s.format
            ));
        }
        Ok(s)
    }

    /// The state in `dir`, if there is one.
    pub fn read(dir: &Path) -> Result<Option<Self>, String> {
        let path = dir.join(STATE_FILE);
        match std::fs::read_to_string(&path) {
            Ok(t) => Self::parse(&t).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(format!("reading {}: {e}", path.display())),
        }
    }

    pub fn to_toml(&self) -> String {
        format!(
            "# Asset slot state (docs/stubs.md): what fills each slot now and where it came from.\n{}",
            toml::to_string(self).expect("the state serializes")
        )
    }
}

/// The state file's JSON Schema, for `gp model schema slots`.
pub fn schema() -> String {
    let mut s = schemars::schema_for!(State);
    s.insert("$id".into(), format!("game-printer:slots@{FORMAT}").into());
    let mut text = serde_json::to_string_pretty(&s).expect("schemas serialize");
    text.push('\n');
    text
}

pub use gp_theme::format::sha256_hex;

/// The digest of a set of files by name: `sha256sum` lines sorted by name,
/// hashed again, as the template manifest's `lifted_sha256` is.
pub fn files_digest(files: &BTreeMap<String, Vec<u8>>) -> String {
    let mut lines = String::new();
    for (name, bytes) in files {
        let _ = writeln!(lines, "{}  {name}", sha256_hex(bytes));
    }
    sha256_hex(lines.as_bytes())
}

/// The digest of one asset's files in a directory.
pub fn asset_digest(dir: &Path, asset: &Asset) -> Result<String, String> {
    let mut files = BTreeMap::new();
    for f in asset.files() {
        let bytes = std::fs::read(dir.join(&f)).map_err(|e| format!("reading {f}: {e}"))?;
        files.insert(f, bytes);
    }
    Ok(files_digest(&files))
}

/// Which asset of the map each slot is filled from, checked: every slot's
/// `from` names the map's source and an asset it has.
pub fn slot_assets<'a>(
    model: &'a Model,
    map: &'a AssetMap,
) -> Result<BTreeMap<&'a str, &'a Asset>, String> {
    let mut out = BTreeMap::new();
    for (name, slot) in &model.assets {
        let Some(from) = &slot.from else { continue };
        if from.source != map.source {
            return Err(format!(
                "asset slot `{name}` is filled from `{}`, but the assets are `{}`'s",
                from.source, map.source
            ));
        }
        let asset = map.asset(&from.asset).ok_or(format!(
            "asset slot `{name}` names `{}`, which the asset map doesn't have",
            from.asset
        ))?;
        out.insert(name.as_str(), asset);
    }
    Ok(out)
}

/// The roles whose sprites use each palette, by palette number.
pub fn palette_roles(model: &Model) -> BTreeMap<u32, Vec<&str>> {
    let mut out: BTreeMap<u32, Vec<&str>> = BTreeMap::new();
    for e in model.entities.values() {
        if let Some(sp) = &e.core.sprite {
            let roles = out.entry(sp.palette).or_default();
            if !roles.contains(&e.core.role.as_str()) {
                roles.push(&e.core.role);
            }
        }
    }
    out
}

/// The license of a model's original assets: `LicenseRef-template-source`
/// when the directory holds an open-tier template's manifest
/// (`template.toml` with `tier = "open"`, which `template_fork` copies with
/// the model), and `LicenseRef-own-copy` otherwise.
pub fn original_license(model_dir: &Path) -> &'static str {
    let open = std::fs::read_to_string(model_dir.join("template.toml"))
        .ok()
        .and_then(|t| t.parse::<toml::Table>().ok())
        .and_then(|t| {
            t.get("template")?
                .get("tier")?
                .as_str()
                .map(|s| s == "open")
        })
        .unwrap_or(false);
    if open {
        TEMPLATE_LICENSE
    } else {
        OWN_COPY_LICENSE
    }
}

/// The kind's name as the model writes it (`level-grid`).
pub fn kind_name(kind: AssetKind) -> String {
    serde_json::to_value(kind)
        .ok()
        .and_then(|v| v.as_str().map(str::to_owned))
        .unwrap_or_default()
}

/// What a replacement must keep: the dimensions and formats `pack` holds a
/// file to, from the map entry.
pub fn shape(asset: &Asset, model: &Model, slot: &str) -> Value {
    match asset {
        Asset::Chr {
            tiles,
            tiles_per_row,
            ..
        } => {
            let (w, h) = gp_assets::chr::image_size(*tiles, *tiles_per_row);
            json!({
                "tile_size": [8, 8],
                "tiles": tiles,
                "tiles_per_row": tiles_per_row,
                "image_size": [w, h],
                "colors": 4,
                "pixels": "indexed PNG, color index 0 to 3; index 0 is transparent in sprites; pixels past the last tile are index 0",
            })
        }
        Asset::Palette { count, .. } => {
            let mut v = json!({
                "palettes": count,
                "colors_per_palette": 4,
                "color_space": "nes-ppu, 0x00 to 0x3F",
            });
            if *count == 8 {
                v["layout"] = json!(
                    "0 to 3 background, 4 to 7 sprites; each sprite palette's index 0 is transparent and background 0's is the backdrop"
                );
            }
            v
        }
        Asset::Metatiles {
            count,
            names,
            properties,
            ..
        } => json!({
            "metatiles": count,
            "tiles_per_metatile": [2, 2],
            "names": names,
            "art_fields": ["tiles"],
            "simulation_fields": properties.iter().map(|p| p.name.clone()).collect::<Vec<_>>(),
        }),
        Asset::Level {
            width,
            height,
            legend,
            ..
        } => {
            let mut v = json!({ "size": [width, height], "legend": legend });
            if let Some(l) = model
                .levels
                .values()
                .find(|l| l.core.grid.as_deref() == Some(slot))
            {
                v["cell_size"] = json!(l.core.tile_size);
            }
            v
        }
        Asset::Table { count, columns, .. } => json!({
            "rows": count,
            "columns": columns.iter().map(|c| c.name.clone()).collect::<Vec<_>>(),
        }),
        _ => json!({}),
    }
}

/// The entities that draw from a slot: by their sprite's tiles, or by the
/// palettes their sprites use. For a tiles slot each gives the image an
/// `assets_place` with `entity` takes.
pub fn used_by(model: &Model, slot: &str, kind: AssetKind) -> Vec<Value> {
    let roles = palette_roles(model);
    let mut out = Vec::new();
    for (name, e) in &model.entities {
        let Some(sp) = &e.core.sprite else { continue };
        let mut v = match kind {
            AssetKind::Tiles if sp.slot == slot => {
                let rows = (sp.tiles.len() as u32).div_ceil(sp.width.max(1));
                json!({
                    "tiles": sp.tiles,
                    "width": sp.width,
                    "image_size": [sp.width * 8, rows * 8],
                    "flip_when_facing_left": sp.flip_when_facing_left,
                })
            }
            AssetKind::Palettes => {
                let mut v = json!({});
                if roles.get(&sp.palette).is_some_and(|r| r.len() > 1) {
                    v["shared"] = json!(true);
                }
                v
            }
            _ => continue,
        };
        v["entity"] = json!(name);
        v["role"] = json!(e.core.role);
        v["palette"] = json!(sp.palette);
        out.push(v);
    }
    out
}

/// The checks a replacement must pass, as the tools report them.
pub fn accept(asset: &Asset, reads_simulation: bool) -> Vec<&'static str> {
    let mut out = vec![
        "format: the file parses and encodes in the map's span (gp assets pack)",
        "model: the slot still fits the model (gp model check --assets)",
    ];
    match asset {
        Asset::Chr { .. } => out.push(
            "shape: the image size and tile count are unchanged, every pixel is index 0 to 3, and pixels past the last tile are index 0",
        ),
        Asset::Palette { .. } => {
            out.push("shape: the palette count is unchanged; every color is an NES color number")
        }
        _ => {}
    }
    out.push(if reads_simulation {
        "simulation: the simulation reads this slot, so a replacement is a model change held to the contract"
    } else {
        "simulation: the state digest of every baseline is unchanged"
    });
    out
}

/// One slot's record: the specification, worked out from the model, the
/// contract and the map (when there is one), and the state, when there
/// is one. With the assets' directory, each slot's files are checked
/// against the digest its state records, and a slot whose files differ is
/// `modified`.
pub fn record(
    model: &Model,
    contract: Option<&Contract>,
    map: Option<&AssetMap>,
    state: Option<&State>,
    dir: Option<&Path>,
    name: &str,
) -> Value {
    let slot = &model.assets[name];
    let reads_sim = gp_interp::lifted::simulation_slots(model)
        .iter()
        .any(|s| s.as_str() == name);
    let mut v = json!({
        "name": name,
        "kind": kind_name(slot.kind),
        "role": slot.role,
        "from": slot.from,
        "reads": if reads_sim { "simulation" } else { "presentation" },
    });
    if let Some(d) = &slot.description {
        v["description"] = json!(d);
    }
    if !slot.item_roles.is_empty() {
        v["item_roles"] = json!(slot.item_roles);
    }
    if let Some(c) = contract {
        let path = [Step::Key("assets".into()), Step::Key(name.into())];
        v["contract_level"] = json!(c.bind(model).resolve(&path, None).level.name());
    }
    let asset = map.and_then(|m| {
        slot.from
            .as_ref()
            .filter(|f| f.source == m.source)
            .and_then(|f| m.asset(&f.asset))
    });
    if let Some(a) = asset {
        v["format"] = json!(a.format());
        v["files"] = json!(a.files());
        v["shape"] = shape(a, model, name);
        v["accept"] = json!(accept(a, reads_sim));
    }
    let users = used_by(model, name, slot.kind);
    if !users.is_empty() {
        v["used_by"] = json!(users);
    }
    match state.and_then(|s| s.slots.get(name)) {
        Some(s) => {
            v["status"] = json!(s.status.name());
            v["provenance"] = serde_json::to_value(s).expect("a slot state serializes");
            if let Some(p) = v["provenance"].as_object_mut() {
                p.remove("status");
            }
            if let (Some(a), Some(d)) = (asset, dir) {
                match asset_digest(d, a) {
                    Ok(now) if now == s.sha256 => {}
                    Ok(now) => {
                        v["status"] = json!(MODIFIED);
                        v["files_sha256"] = json!(now);
                    }
                    Err(e) => {
                        v["status"] = json!(MODIFIED);
                        v["files_error"] = json!(e);
                    }
                }
            }
        }
        None => {
            v["status"] = json!(if asset.is_some() { "original" } else { "empty" });
        }
    }
    v
}

/// Every slot's record, in name order.
pub fn records(
    model: &Model,
    contract: Option<&Contract>,
    map: Option<&AssetMap>,
    state: Option<&State>,
    dir: Option<&Path>,
) -> Vec<Value> {
    model
        .assets
        .keys()
        .map(|n| record(model, contract, map, state, dir, n))
        .collect()
}

/// True when a slot's content is, at least in part, an original asset of
/// a commercial source: lifted from the person's own copy, which is never
/// shared. That's an original of a model that isn't an open-tier
/// template's (`open_tier`, from [`is_open_tier`]), or any slot whose
/// license names `LicenseRef-own-copy`, as one only partly replaced does
/// (`LicenseRef-own-copy AND CC0-1.0`).
pub fn holds_commercial_original(state: &SlotState, open_tier: bool) -> bool {
    state.license.contains(OWN_COPY_LICENSE) || (state.status == Status::Original && !open_tier)
}

/// True when the directory holds an open-tier template's manifest.
pub fn is_open_tier(model_dir: &Path) -> bool {
    original_license(model_dir) == TEMPLATE_LICENSE
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_round_trips_and_refuses_unknown_keys() {
        let mut s = State::new("example");
        s.slots.insert(
            "tiles".into(),
            SlotState {
                status: Status::Stub,
                origin: Origin::Stub,
                license: STUB_LICENSE.into(),
                sha256: "00".repeat(32),
                generator: Some("gp assets stub".into()),
                author: None,
                note: None,
            },
        );
        let text = s.to_toml();
        assert_eq!(State::parse(&text).unwrap(), s);
        assert!(State::parse(&text.replace("status", "statue")).is_err());
        assert!(State::parse(&text.replace("0.1.0", "9.0.0")).is_err());
    }

    #[test]
    fn digests_are_sha256sum_lines() {
        let files = BTreeMap::from([("a".to_owned(), b"x".to_vec())]);
        // printf 'x' | sha256sum, then that line hashed again.
        let line = format!("{}  a\n", sha256_hex(b"x"));
        assert_eq!(files_digest(&files), sha256_hex(line.as_bytes()));
    }
}
